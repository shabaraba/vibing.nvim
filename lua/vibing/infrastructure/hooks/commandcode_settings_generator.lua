--- How the PreToolUse gate reaches Command Code: the `mod_file` transport.
---
--- Command Code reads Claude-shaped hooks from `.commandcode/settings.json` and
--- `settings.local.json`, but it has **no `--settings` flag, no config-content environment, and no
--- plugin directory** — and both files it does read are the user's own. So none of the five
--- transports before this one fits, and writing into the user's settings is not an option.
---
--- The one per-run extension point is `--mod <path>`: a TypeScript file whose
--- `cmd.hooks({beforeToolCall})` may block a tool. It loads in **both** transports — under `-p`
--- print mode and with the `acp` subcommand (measured on 1.88.2; print mode loads user-scope and
--- `--mod` mods, and the flag is accepted ahead of the subcommand). So this generator writes that
--- mod, and it spawns the same `bin/hooks/pre-tool-use.sh` every other backend uses and reads its
--- exit code under the same `claude` dialect — a second implementation of "what a decision means"
--- is the failure the shared script exists to prevent (`pi-extension` states the same rule).
---
--- Two consequences of the shape:
---
--- **Nothing is keyed by instance.** The other generators key their output by
--- `rpc/instance_key.lua` because the file carries a timeout derived from
--- `permissions.approval_wait_sec`, and a second Neovim rewriting it could put the CLI's deadline
--- ahead of the script's. Here the deadline never lands in the file — it reaches the mod in the
--- child's environment (`commandcode_command_builder.apply_env`), fixed at spawn — so the file's
--- bytes do not depend on configuration and are identical for every instance.
---
--- **Expiry here fails closed.** A `beforeToolCall` that blocks is a tool that does not run, so the
--- mod's own timeout denies, and the `approval_wait_sec < script wait < mod timeout` ordering only
--- keeps a slow-but-answered approval from being cut short — the same inversion
--- `pi_settings_generator` documents.
--- @module vibing.infrastructure.hooks.commandcode_settings_generator

local Fs = require("vibing.core.utils.fs")

local M = {}

--- The PreToolUse timeout this transport applies, in seconds.
---
--- Command Code imposes none of its own on a mod hook, so — as with Pi's extension — this number is
--- the deadline the bridge itself enforces, handed to it in `VIBING_COMMANDCODE_HOOK_TIMEOUT_SEC`.
--- @return number seconds
function M.hook_timeout_sec()
  return require("vibing.infrastructure.hooks.wait_budget").cli_timeout_sec()
end

local MOD_DIR = "commandcode-mod"
local MOD_FILE = "vibing-nvim-permissions.ts"

--- The TypeScript bridge. Static — every value it needs arrives in the environment — so it is
--- written verbatim and never interpolated.
local MOD_SOURCE = [[
/**
 * vibing.nvim's permission bridge for Command Code.
 *
 * Command Code's own headless gate is all-or-nothing (it refuses writes and shell unless `--yolo`
 * is passed), so vibing.nvim runs the CLI in bypass and this bridge — plus the shared
 * `bin/hooks/pre-tool-use.sh` it spawns — is the gate. A decision is never re-implemented here:
 * the script's exit code is read under the same `claude` dialect every other backend uses.
 *
 * Generated by lua/vibing/infrastructure/hooks/commandcode_settings_generator.lua. Do not edit.
 */

import { spawn } from 'node:child_process';

const SCRIPT_VAR = 'VIBING_COMMANDCODE_HOOK_SCRIPT';
const TIMEOUT_VAR = 'VIBING_COMMANDCODE_HOOK_TIMEOUT_SEC';
const FALLBACK_TIMEOUT_SEC = 990;

interface Verdict {
  block?: boolean;
  additionalContext?: string;
}

interface BeforeToolCallArgs {
  toolName: string;
  input?: Record<string, unknown>;
}

interface ModApi {
  hooks: (hooks: {
    beforeToolCall?: (args: BeforeToolCallArgs, ctx?: { signal?: AbortSignal }) => Promise<Verdict | undefined>;
  }) => unknown;
}

function timeoutSec(): number {
  const raw = Number(process.env[TIMEOUT_VAR]);
  return Number.isFinite(raw) && raw > 0 ? raw : FALLBACK_TIMEOUT_SEC;
}

function askNeovim(
  script: string,
  payload: unknown,
  signal?: AbortSignal
): Promise<Verdict | undefined> {
  return new Promise((resolve) => {
    let child: ReturnType<typeof spawn>;
    try {
      child = spawn(script, [], { stdio: ['pipe', 'pipe', 'pipe'] });
    } catch (err) {
      resolve({ block: true, additionalContext: 'vibing.nvim permission bridge could not start: ' + String(err) });
      return;
    }

    let stderr = '';
    let settled = false;
    const finish = (verdict: Verdict | undefined) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      signal?.removeEventListener('abort', onAbort);
      resolve(verdict);
    };

    const timer = setTimeout(() => {
      child.kill('SIGKILL');
      finish({ block: true, additionalContext: 'vibing.nvim permission check timed out after ' + timeoutSec() + 's' });
    }, timeoutSec() * 1000);

    const onAbort = () => {
      child.kill('SIGKILL');
      finish({ block: true, additionalContext: 'Cancelled' });
    };
    signal?.addEventListener('abort', onAbort, { once: true });

    child.stderr?.on('data', (chunk) => {
      stderr += String(chunk);
    });
    child.on('error', (err) =>
      finish({ block: true, additionalContext: 'vibing.nvim permission bridge failed: ' + err.message })
    );
    child.on('close', (code) => {
      if (code === 0) {
        finish(undefined);
        return;
      }
      if (code === 2) {
        finish({ block: true, additionalContext: stderr.trim() || 'Denied by vibing.nvim' });
        return;
      }
      finish({
        block: true,
        additionalContext: 'vibing.nvim permission bridge exited with ' + String(code) + ': ' + stderr.trim(),
      });
    });

    child.stdin?.on('error', () => {
      /* the script exited before reading; `close` above carries the verdict */
    });
    // The CLI's own PreToolUse wire shape, so the vocabulary's normalisation is the one the
    // permission handler already runs for every backend.
    child.stdin?.end(
      JSON.stringify({
        hook_event_name: 'PreToolUse',
        tool_name: payload.toolName,
        tool_input: payload.input || {},
        cwd: process.cwd(),
      })
    );
  });
}

export default function (cmd: ModApi): void {
  cmd.hooks({
    beforeToolCall: async ({ toolName, input }, ctx) => {
      const script = process.env[SCRIPT_VAR];
      if (!script) {
        // A plain `commandcode` session that happened to load this file has nothing to ask;
        // refusing every call would break it. The shared script makes the same judgement from
        // `VIBING_NVIM_RPC_PORT`, which is absent in that case.
        if (!process.env.VIBING_NVIM_RPC_PORT) return undefined;
        return {
          block: true,
          additionalContext: 'vibing.nvim permission bridge is not configured (' + SCRIPT_VAR + ' unset)',
        };
      }
      return await askNeovim(script, { toolName, input }, ctx?.signal);
    },
  });
}
]]

--- @param cwd string
--- @return string absolute path to the generated mod file
function M.mod_path(cwd)
  return vim.fn.resolve(cwd) .. "/.vibing/" .. MOD_DIR .. "/" .. MOD_FILE
end

--- Write the bridge and return the path `--mod` should point at.
---
--- Written atomically (tmp + rename) like the other generated files: a `--mod` file that is read
--- half-written is a mod that fails to load, and a mod that fails to load is a gate that is not
--- there — Command Code reports it as a warning and carries on.
--- @param cwd? string
--- @param _dialect? string unused; the bridge reads the script's exit code, which is the `claude` branch
--- @return string path
function M.ensure(cwd, _dialect)
  local resolved = vim.fn.resolve(cwd or vim.fn.getcwd())
  local dir = resolved .. "/.vibing/" .. MOD_DIR
  Fs.ensure_dir(dir)

  local path = dir .. "/" .. MOD_FILE
  local tmp_path = string.format("%s.%d.tmp", path, vim.loop.getpid())
  local f, err = io.open(tmp_path, "w")
  if not f then
    error("Failed to create Command Code mod: " .. tmp_path .. " (" .. tostring(err) .. ")")
  end
  f:write(MOD_SOURCE)
  f:close()

  local ok, rename_err = os.rename(tmp_path, path)
  if not ok then
    os.remove(tmp_path)
    error("Failed to install Command Code mod: " .. path .. " (" .. tostring(rename_err) .. ")")
  end

  return path
end

return M
